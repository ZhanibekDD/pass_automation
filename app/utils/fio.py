"""Разбор ФИО для заполнения колонок реестра (фамилия / имя / отчество)."""


def split_fio(fio: str) -> tuple[str, str, str]:
    """
    Делит строку ФИО на (фамилия, имя, отчество).

    Правило: слова по пробелам; при >=3 словах отчество — всё после второго слова
    (двойные фамилии/отчества через пробел окажутся в хвосте отчества — уточнять под процесс).
    """
    parts = fio.strip().split()
    if len(parts) >= 3:
        return parts[0], parts[1], " ".join(parts[2:])
    if len(parts) == 2:
        return parts[0], parts[1], ""
    if len(parts) == 1:
        return parts[0], "", ""
    return "", "", ""
